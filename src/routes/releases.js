function assetCountLabel(assetIds) {
  const count = new Set(assetIds).size;
  return `${count} asset${count === 1 ? '' : 's'}`;
}

function readSelectedAssetsReleaseReturnLocation(candidate, projectId) {
  if (!isSafeRedirectTarget(candidate)) return '';

  try {
    const url = new URL(candidate, 'http://creatorcrate.local');
    if (url.origin !== 'http://creatorcrate.local' || url.pathname !== `/projects/${projectId}/assets`) return '';
    return `${url.pathname}${url.search}${url.hash}`;
  } catch {
    return '';
  }
}

// The canonical Edit Release deep link (also generated by the Calendar and
// Dashboard Edit actions): Release Detail loads and opens its shared async
// Edit dialog for this release (release-edit-dialog.js).
function buildReleaseEditDeepLink(releaseId) {
  return `/releases/${releaseId}?edit=1`;
}

