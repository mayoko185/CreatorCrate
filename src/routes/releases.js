function releaseListQueryFromSearchParams(searchParams) {
  const query = {};
  for (const [key, value] of searchParams) {
    if (!Object.hasOwn(query, key)) {
      query[key] = value;
    } else if (Array.isArray(query[key])) {
      query[key].push(value);
    } else {
      query[key] = [query[key], value];
    }
  }
  return query;
}

// Only the exact Dashboard path or a canonical /releases list location can
// host a create-validation rerender; anything else falls back to the
// standalone form.
function readReleaseCreateDialogContext(body) {
  const candidate = body?.returnTo;
  if (candidate === '/') return { host: '/', invocationReturnTo: '', listQuery: null };
  if (!isSafeRedirectTarget(candidate)) return null;

  try {
    const url = new URL(candidate, 'http://creatorcrate.local');
    if (url.origin !== 'http://creatorcrate.local' || url.pathname !== '/releases') return null;
    return {
      host: '/releases',
      invocationReturnTo: `${url.pathname}${url.search}${url.hash}`,
      listQuery: releaseListQueryFromSearchParams(url.searchParams),
    };
  } catch {
    return null;
  }
}

function renderReleaseCreateError(req, res, next, {
  appName,
  projectService,
  workflowQueryService,
  errors,
  values = req.body,
  selectedAssetsFlow = false,
  selectedAssetsReturnTo = '',
  selectedAssetsInvalid = false,
  selectedAssetsRecoveryUrl = null,
}) {
  const createDialogContext = selectedAssetsFlow ? null : readReleaseCreateDialogContext(req.body);
  const releaseCreateForm = buildCreateReleaseFormModel({
    appName,
    projectService,
    values,
    errors,
    selectedAssetsFlow,
    selectedAssetsReturnTo,
    selectedAssetsInvalid,
    selectedAssetsRecoveryUrl,
    isFreshCreate: false,
    invocationReturnTo: createDialogContext?.invocationReturnTo || '',
  });

  if (createDialogContext?.host === '/') {
    renderDashboardPage(req, res, next, {
      appName,
      workflowQueryService,
      projectService,
      status: 422,
      releaseCreateDialogOpen: true,
      releaseCreateForm,
    });
    return;
  }

  if (selectedAssetsFlow || createDialogContext) {
    handleReleaseList(req, res, next, {
      appName,
      projectService,
      workflowQueryService,
      status: 422,
      releaseCreateDialogOpen: true,
      releaseCreateForm,
      allowSavedDefaultsRedirect: false,
      notice: null,
      pagePath: '/',
      listQuery: createDialogContext?.listQuery || req.query,
    });
    return;
  }

  res.status(422).render('releases/form.njk', {
    ...releaseCreateForm,
    releaseSignatureConfiguration: getReleaseSignatureConfiguration(req),
    platformChoices: getReleasePlatformChoices(req),
  });
}

/**
 * GET /releases list handler.
 * @param {import('express').Request} req
 * @param {import('express').Response} res
 * @param {import('express').NextFunction} next
 * @param {object} deps - { appName, projectService, workflowQueryService }
 */
function handleReleaseList(
  req,
  res,
  next,
  {
    appName,
    projectService,
    workflowQueryService,
    status = 200,
    releaseCreateDialogOpen = false,
    releaseCreateForm = null,
    defaultsDialogOpen = req.query?.defaults === '1',
    defaultsSubmittedValues = null,
    defaultsErrors = {},
    allowSavedDefaultsRedirect = req.query?.defaults !== '1',
    notice = resolveReleasesNotice(req.query?.notice),
    pagePath = req.path,
    listQuery = req.query,
  },
) {
  try {
    const pageDefaultsService = getReleasePageDefaultsService(req, RELEASES_PAGE_DEFAULTS);
    const rawQuery = listQuery && typeof listQuery === 'object' ? listQuery : {};
    const normalizedRawQuery = omitLegacyStatusField(rawQuery);
    const assetScope = resolveReleaseListAssetScope(req, normalizedRawQuery, projectService);
    const presentation = resolveReleasePresentation(normalizedRawQuery, pageDefaultsService, RELEASES_PAGE_DEFAULTS);
    const effectiveQuery = {
      ...normalizedRawQuery,
      sort: presentation.sort,
      order: presentation.order,
    };
    const normalizedFilters = workflowQueryService.normalizeListFilters(effectiveQuery);
    const projectOptions = workflowQueryService.getProjectsPageFilterOptions(normalizedFilters.projectId);
    const basePath = req.baseUrl;
    const pageUrlRequest = pagePath === req.path ? req : { baseUrl: req.baseUrl, path: pagePath };

    // Release lists always use the list presentation; legacy view query values
    // are intentionally ignored so existing board URLs remain safe.
    const { releases, total, page, pageSize, pageCount, today, hasAnyReleases } = workflowQueryService.getReleaseList(effectiveQuery);
    const urlQuery = buildReleaseManagementUrlQuery(normalizedFilters, presentation, page);
    if (allowSavedDefaultsRedirect && shouldRedirectToSavedReleaseManagementDefaults(
      normalizedRawQuery,
      presentation,
      { preserveDefaultsDialog: true },
    )) {
      return res.redirect(buildPageUrl(pageUrlRequest, urlQuery)({}));
    }
    const pageUrl = buildPageUrl(pageUrlRequest, urlQuery);
    const query = buildReleaseManagementRenderQuery(normalizedFilters, presentation, page);
    const clearUrl = buildPageUrl(
      pageUrlRequest,
      buildReleaseManagementUrlQuery(
        normalizedFilters,
        presentation,
        page,
      ),
    )(buildReleaseManagementClearOverrides());

    res.status(status).render('releases/index.njk', {
      appName,
      releases,
      total,
      page,
      pageSize,
      pageCount,
      today,
      hasAnyReleases,
      pageUrl,
      clearUrl,
      query,
      projectOptions,
      selectedProjectId: normalizedFilters.projectId,
      assetScope,
      releasesDefaultsAction: buildReleasesDefaultsAction(urlQuery),
      sortOptions: SORT_OPTIONS,
      basePath,
      releasesLiveFiltering: true,
      releaseCreateDialogOpen: Boolean(releaseCreateDialogOpen),
      releaseSignatureConfiguration: getReleaseSignatureConfiguration(req),
      platformChoices: getReleasePlatformChoices(req),
      releaseCreateForm: releaseCreateForm || buildCreateReleaseFormModel({
        appName,
        projectService,
      }),
      ...buildReleasesRenderExtras({
        pageDefaultsService,
        defaultsDialogOpen,
        defaultsSubmittedValues,
        defaultsErrors,
        notice,
      }),
    });
  } catch (err) {
    next(err);
  }
}

